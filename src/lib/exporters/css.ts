import type { ExportSettings, Project } from '@/types';
import { resolveRoles, type RoleToken } from '@/lib/tokens/roles';
import { derivePrimitives, formatValue, type ExportResult } from './primitives';

/** A role's CSS value: a reference to its primitive, or a literal colour. */
export function roleValue(role: RoleToken, format: ExportSettings['colourFormat']): string {
  return role.ref ? `var(--color-${role.ref})` : formatValue(role, format);
}

export const includesRoles = (settings: ExportSettings) => settings.scope !== 'primitive';

/** CSS custom properties: `--color-{family}-{step}` on :root (EX-001), plus role tokens for light and dark when asked for. */
export function exportCss(project: Project, settings: ExportSettings): ExportResult {
  const lines: string[] = [`/* ${project.name} — colour primitives. Generated by Palette AI. */`, ':root {'];
  project.colourFamilies.forEach((family, i) => {
    if (i > 0) lines.push('');
    lines.push(`  /* ${family.familyName} */`);
    for (const token of derivePrimitives([family])) {
      lines.push(`  --color-${token.name}: ${formatValue(token, settings.colourFormat)};`);
    }
  });
  lines.push('}', '');
  const roles = includesRoles(settings) ? resolveRoles(project) : null;
  if (roles) {
    lines.push('/* Role tokens — light theme (default). */', ':root {');
    for (const role of roles.light) lines.push(`  --color-${role.name}: ${roleValue(role, settings.colourFormat)};`);
    lines.push('}', '', '/* Role tokens — dark theme. Put data-theme="dark" or class "dark" on <html>. */', "[data-theme='dark'],", '.dark {');
    for (const role of roles.dark) lines.push(`  --color-${role.name}: ${roleValue(role, settings.colourFormat)};`);
    lines.push('}', '');
  }
  return { filename: 'colors.css', mime: 'text/css', content: lines.join('\n') };
}
