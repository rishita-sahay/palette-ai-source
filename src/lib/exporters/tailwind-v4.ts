import type { ExportSettings, Project } from '@/types';
import { derivePrimitives, formatValue, type ExportResult } from './primitives';

/**
 * Tailwind CSS v4, CSS-first: theme variables inside `@theme`. Each `--color-{family}-{step}`
 * becomes utilities such as `bg-primary-500` / `text-neutral-900` (EX-002).
 * This is a separate code path from any v3 `tailwind.config.js` export.
 */
export function exportTailwindV4(project: Project, settings: ExportSettings): ExportResult {
  const lines: string[] = [
    `/* ${project.name} — Tailwind CSS v4 theme. Generated by Palette AI. */`,
    '@import "tailwindcss";',
    '',
    '@theme {',
  ];
  project.colourFamilies.forEach((family, i) => {
    if (i > 0) lines.push('');
    lines.push(`  /* ${family.familyName} */`);
    for (const token of derivePrimitives([family])) {
      lines.push(`  --color-${token.name}: ${formatValue(token, settings.colourFormat)};`);
    }
  });
  lines.push('}', '');
  return { filename: 'theme.css', mime: 'text/css', content: lines.join('\n') };
}
